CREATE TABLE `word_review_record` (
    `id` bigint unsigned NOT NULL AUTO_INCREMENT,
    `progress_id` bigint unsigned NOT NULL,
    `user_id` bigint unsigned NOT NULL,
    `word_id` bigint unsigned NOT NULL,
    `card_type` varchar(32) NOT NULL,
    `rating` tinyint unsigned NOT NULL COMMENT '1=忘记,2=困难,3=记得,4=容易',
    `reviewed_at` datetime(3) NOT NULL COMMENT 'UTC评分时间',
    `due_before` datetime(3) DEFAULT NULL,
    `due_after` datetime(3) NOT NULL,
    `elapsed_ms` int unsigned DEFAULT NULL COMMENT '客户端用时，仅供统计',
    `scheduler_version` varchar(32) NOT NULL,
    `desired_retention` decimal(4,3) NOT NULL,
    `state_after` varchar(16) NOT NULL,
    `version_after` int unsigned NOT NULL,
    `request_id` varchar(64) NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_user_request` (`user_id`, `request_id`),
    KEY `idx_user_reviewed` (`user_id`, `reviewed_at`),
    KEY `idx_progress_reviewed` (`progress_id`, `reviewed_at`),
    CONSTRAINT `fk_review_progress` FOREIGN KEY (`progress_id`) REFERENCES `word_learning_progress` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_review_user` FOREIGN KEY (`user_id`) REFERENCES `user` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_review_word` FOREIGN KEY (`word_id`) REFERENCES `word_dictionary` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='不可覆盖的单词评分记录';
