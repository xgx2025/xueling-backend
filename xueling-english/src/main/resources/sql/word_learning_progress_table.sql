CREATE TABLE `word_learning_progress` (
    `id` bigint unsigned NOT NULL AUTO_INCREMENT,
    `user_id` bigint unsigned NOT NULL,
    `word_id` bigint unsigned NOT NULL,
    `card_type` varchar(32) NOT NULL DEFAULT 'EN_ZH',
    `state` varchar(16) NOT NULL,
    `card_json` json NOT NULL COMMENT 'Java-FSRS Card序列化状态',
    `due_at` datetime(3) NOT NULL COMMENT 'UTC到期时间',
    `last_review_at` datetime(3) DEFAULT NULL COMMENT 'UTC评分时间',
    `introduced_date` date NOT NULL COMMENT '首次学习时用户所在时区的日期',
    `review_count` int unsigned NOT NULL DEFAULT 0,
    `lapse_count` int unsigned NOT NULL DEFAULT 0,
    `scheduler_version` varchar(32) NOT NULL,
    `version` int unsigned NOT NULL DEFAULT 1,
    `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `update_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_user_word_type` (`user_id`, `word_id`, `card_type`),
    KEY `idx_user_card_due` (`user_id`, `card_type`, `due_at`),
    KEY `idx_user_introduced` (`user_id`, `introduced_date`),
    CONSTRAINT `fk_learning_user` FOREIGN KEY (`user_id`) REFERENCES `user` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_learning_word` FOREIGN KEY (`word_id`) REFERENCES `word_dictionary` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户单词记忆卡片';
